import type { Editorial, Snapshot } from "./schema.ts";
import { validateCatalogue } from "./validate.ts";

function tally(values: (string | number)[]): Record<string, number> {
  const result: Record<string, number> = {};
  for (const value of values) result[value] = (result[value] ?? 0) + 1;
  return Object.fromEntries(
    Object.entries(result).sort(([a], [b]) => a.localeCompare(b)),
  );
}

export function catalogueReport(editorial: Editorial, snapshot: Snapshot): string {
  const entries = editorial.entries;
  const publication = validateCatalogue(editorial, snapshot, "publication");
  const entryIds = new Set(entries.map((entry) => entry.id));
  const globalErrors = publication.some((issue) => !entryIds.has(issue.entryId));
  const counts = {
    entries: entries.length,
    distinctGridAnswers: new Set(entries.map((item) => item.answer.grid)).size,
    sources: snapshot.sources.length,
    evidencePassages: snapshot.evidence.length,
    publicationReadyEntries: entries.filter(
      (entry) =>
        !globalErrors && !publication.some((issue) => issue.entryId === entry.id),
    ).length,
    answerKinds: tally(entries.map((item) => item.answer.kind)),
    lengths: tally(entries.map((item) => item.answer.grid.length)),
    difficulties: tally(entries.map((item) => item.difficulty)),
    disclosedBy: tally(entries.map((item) => item.disclosedBy)),
    exposure: tally(entries.map((item) => item.exposure)),
    status: tally(entries.map((item) => item.status)),
    topics: tally(entries.flatMap((item) => item.topics)),
  };
  const table = entries
    .map(
      (entry) =>
        `| ${entry.answer.display} | ${entry.answer.enumeration.join(",")} | ${entry.difficulty} | ${entry.clue.text} | ${entry.hint.text} |`,
    )
    .join("\n");
  return `# Editorial seed report\n\nGenerated by \`pnpm content:report\`. Counts describe this seed, not all Warcraft.\n\n\`\`\`json\n${JSON.stringify(counts, null, 2)}\n\`\`\`\n\nAll difficulty ratings are editorial hypotheses. Source checks verify references and exact excerpts, not whether a clue is fun or logically sufficient. Publication requires a cold review.\n\n| Answer | Lengths | Difficulty | Clue | Hint |\n| --- | --- | --- | --- | --- |\n${table}\n`;
}
