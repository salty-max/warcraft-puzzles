import type { Editorial, Snapshot } from "./schema.ts";
import { validateCatalogue } from "./validate.ts";

function tally(values: (string | number)[]): Record<string, number> {
  const result: Record<string, number> = {};
  for (const value of values) result[value] = (result[value] ?? 0) + 1;
  return Object.fromEntries(
    Object.entries(result).sort(([a], [b]) => a.localeCompare(b)),
  );
}

export function catalogueReport(editorial: Editorial, snapshot: Snapshot): string {
  const entries = editorial.entries;
  const publication = validateCatalogue(editorial, snapshot, "publication");
  const entryIds = new Set(entries.map((entry) => entry.id));
  const globalErrors = publication.some((issue) => !entryIds.has(issue.entryId));
  const gridAnswers = [...new Set(entries.map((entry) => entry.answer.grid))];
  const sharedPassages = snapshot.evidence
    .filter((item) => item.locator.table !== "name")
    .map((item) => ({
      id: item.id,
      answers: entries
        .filter((entry) => entry.fact.evidenceIds.includes(item.id))
        .map((entry) => entry.answer.display),
    }))
    .filter((item) => item.answers.length > 1)
    .sort((a, b) => b.answers.length - a.answers.length || a.id.localeCompare(b.id));
  const counts = {
    entries: entries.length,
    distinctGridAnswers: new Set(entries.map((item) => item.answer.grid)).size,
    sources: snapshot.sources.length,
    evidenceRecords: snapshot.evidence.length,
    evidenceTables: tally(snapshot.evidence.map((item) => item.locator.table)),
    multiwordEntries: entries.filter((entry) => entry.answer.enumeration.length > 1)
      .length,
    shortDistinctAnswers: gridAnswers.filter((answer) => answer.length <= 4).length,
    lengthEligibleDistinctAnswersByGridSize: Object.fromEntries(
      [5, 7, 9, 11, 13].map((size) => [
        size,
        gridAnswers.filter((answer) => answer.length <= size).length,
      ]),
    ),
    sharedTextPassages: sharedPassages.length,
    publicationReadyEntries: entries.filter(
      (entry) =>
        !globalErrors && !publication.some((issue) => issue.entryId === entry.id),
    ).length,
    answerKinds: tally(entries.map((item) => item.answer.kind)),
    lengths: tally(entries.map((item) => item.answer.grid.length)),
    difficulties: tally(entries.map((item) => item.difficulty)),
    disclosedBy: tally(entries.map((item) => item.disclosedBy)),
    exposure: tally(entries.map((item) => item.exposure)),
    status: tally(entries.map((item) => item.status)),
    topics: tally(entries.flatMap((item) => item.topics)),
  };
  const table = entries
    .map(
      (entry) =>
        `| ${entry.answer.display} | ${entry.answer.enumeration.join(",")} | ${entry.difficulty} | ${entry.clue.text} | ${entry.hint.text} |`,
    )
    .join("\n");
  const overlap = sharedPassages.length
    ? `| Source passage | Related entries |\n| --- | --- |\n${sharedPassages.map((item) => `| ${item.id} | ${item.answers.join(", ")} |`).join("\n")}`
    : "No shared text passages.";
  return `# Editorial seed report\n\nGenerated by \`pnpm content:report\`. Counts describe this seed, not all Warcraft.\n\n\`\`\`json\n${JSON.stringify(counts, null, 2)}\n\`\`\`\n\nAll difficulty ratings are editorial hypotheses. Source checks verify references and exact excerpts, not whether a clue is fun or logically sufficient. Publication requires a cold review.\n\nLength eligibility counts total grid letters, including multi-word entries. It is an upper bound before crossings and layout constraints, not a successful-fill count.\n\n## Triads\n\n| Answer | Lengths | Difficulty | Clue | Hint |\n| --- | --- | --- | --- | --- |\n${table}\n\n## Shared source passages\n\nThese are review prompts for related knowledge, not automatic bans. A passage may support different facts. Avoid filling one puzzle with answers that repeat a fact or disclose one another.\n\n${overlap}\n`;
}
