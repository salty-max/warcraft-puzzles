import { readFileSync, writeFileSync } from "node:fs";
import { format, resolveConfig } from "prettier";
import { parseArgs } from "node:util";
import {
  isWebSource,
  normalizeAnswer,
  validateResearch,
} from "../packages/content/src/index.ts";
import type { Research } from "../packages/content/src/index.ts";
import { loadEditorial, loadResearch, loadResearchSnapshot } from "./io.ts";

// A research batch as something to read: each answer's facts with their sources and
// dates, what was dropped, the new clue and hint beside the old ones, the gates' verdicts.
// Each batch's read-out is docs/research-<batch>.md. With no batch, every batch.
const { values, positionals } = parseArgs({
  allowPositionals: true,
  options: { check: { type: "boolean", default: false } },
});
const batches = loadResearch().filter(
  (item) => !positionals.length || positionals.includes(item.batch),
);
if (positionals.length && !batches.length) {
  throw new Error(`No research batch ${JSON.stringify(positionals.join(" "))}`);
}

export function renderResearch(
  research: Research,
  oldClues: Map<string, { clue: string; hint: string }>,
  named: Map<string, string[]>,
): string {
  const lines = [
    `# Research batch: ${research.batch}`,
    "",
    "Generated by `pnpm content:dossier " +
      research.batch +
      "` from `content/research/" +
      research.batch +
      ".json`. Do not edit by hand.",
    "",
    ...(research.summary ? [research.summary, ""] : []),
    research.attribution,
    "",
  ];
  for (const dossier of research.dossiers) {
    const grid = normalizeAnswer(dossier.answer);
    const { db, kind, id } = dossier.entity;
    lines.push(
      `## ${dossier.answer}`,
      "",
      `${kind} ${id} in ${db}.db${dossier.scope ? `, ${dossier.scope}` : ""}`,
      "",
    );
    if (dossier.notes) lines.push(dossier.notes, "");
    lines.push("Facts:", "");
    for (const fact of dossier.facts) {
      const when = fact.established
        ? ` (${fact.established.by}, ${fact.established.date})`
        : fact.kind === "spelling"
          ? " (spelling cue)"
          : fact.from
            ? ` (from ${fact.from.join(", ")})`
            : "";
      lines.push(`- \`${fact.id}\` ${fact.says}${when}`);
      for (const source of fact.sources) {
        const where = isWebSource(source)
          ? `${source.url}${source.revid ? ` rev ${source.revid}` : ""}${source.cites ? `, citing ${source.cites}` : ""}${source.manual ? ", read by hand" : ""}`
          : `${source.game.db}.db ${source.game.locator.table} ${JSON.stringify(source.game.locator)}`;
        lines.push(`  - "${source.passage}" (${where})`);
      }
    }
    if (dossier.dropped.length) {
      lines.push("", "Dropped:", "");
      for (const drop of dossier.dropped) lines.push(`- ${drop.says}: ${drop.why}`);
    }
    for (const triad of research.triads.filter(
      (item) => normalizeAnswer(item.answer) === grid,
    )) {
      lines.push(
        "",
        `**Clue** (${triad.difficulty}, ${triad.status}): ${triad.clue.text}`,
        "",
        `**Hint:** ${triad.hint.text}`,
      );
      const old = oldClues.get(grid);
      if (old) lines.push("", `Old clue: ${old.clue}`, "", `Old hint: ${old.hint}`);
      const gates = triad.gates;
      if (gates?.coldSolve)
        lines.push(
          "",
          `Cold-solver: ${gates.coldSolve.answer} (${gates.coldSolve.solved ? "solved" : "missed"})`,
        );
      if (gates?.factCheck) lines.push("", `Fact-checker: ${gates.factCheck}`);
      if (gates?.editor) lines.push("", `Editor: ${gates.editor}`);
      const names = named.get(triad.id);
      if (names?.length)
        lines.push("", `Names other banked answers: ${names.join(", ")}`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

const editorial = loadEditorial();
const live = editorial.entries.filter((entry) => entry.status !== "rejected");
const oldClues = new Map(
  live.map((entry) => [
    entry.answer.grid,
    { clue: entry.clue.text, hint: entry.hint.text },
  ]),
);
const snapshot = loadResearchSnapshot();
for (const research of batches) {
  const { notes } = validateResearch(
    research,
    snapshot,
    live.map((entry) => ({ id: entry.id, display: entry.answer.display })),
  );
  const named = new Map<string, string[]>();
  for (const note of notes) {
    const name = /names (.*) \(/.exec(note.message)?.[1] ?? note.message;
    named.set(note.id, [...(named.get(note.id) ?? []), name]);
  }
  const path = `docs/research-${research.batch}.md`;
  // Formatted as the repository formats markdown, so --check and format:check agree.
  const output = await format(renderResearch(research, oldClues, named), {
    ...(await resolveConfig(path)),
    parser: "markdown",
  });
  if (!values.check) writeFileSync(path, output);
  else if (readFileSync(path, "utf8") !== output) {
    console.error(`${path} is stale: run pnpm content:dossier ${research.batch}`);
    process.exitCode = 1;
  }
}
