import { z } from "zod";
import {
  ALGORITHM_VERSION,
  LayoutSchema,
  compileLayout,
  fillGrid,
  inspectFill,
} from "../packages/crossword/src/index.ts";
import type { FillResult } from "../packages/crossword/src/index.ts";
import { sha256, validateCatalogue } from "../packages/content/src/index.ts";
import type { Editorial, Snapshot } from "../packages/content/src/index.ts";

export const BenchmarkConfigSchema = z
  .strictObject({
    schemaVersion: z.literal(1),
    seeds: z.array(z.number().int().min(0).max(0xffffffff)).min(1).max(8),
    nodeLimit: z.number().int().min(1).max(100000),
    layouts: z.array(LayoutSchema).min(1).max(30),
  })
  .refine(
    (config) => new Set(config.seeds).size === config.seeds.length,
    "Seeds must be unique",
  )
  .refine(
    (config) =>
      new Set(config.layouts.map((layout) => layout.id)).size === config.layouts.length,
    "Layout IDs must be unique",
  );
export type BenchmarkConfig = z.infer<typeof BenchmarkConfigSchema>;
export type BenchmarkCase = {
  layoutId: string;
  cohort: "all-triads" | "proper-names-only";
  seed: number;
  result: FillResult;
};
export type Benchmark = ReturnType<typeof runBenchmark>;
export type BenchmarkMeasurement = Pick<
  BenchmarkCase,
  "layoutId" | "cohort" | "seed"
> & { elapsedMs: number };

export function runBenchmark(
  editorial: Editorial,
  snapshot: Snapshot,
  input: unknown,
  onCase?: (measurement: BenchmarkMeasurement) => void,
) {
  const issues = validateCatalogue(editorial, snapshot);
  if (issues.length) throw new Error(`Invalid research catalogue: ${issues[0]!.code}`);
  const config = BenchmarkConfigSchema.parse(input);
  const entries = editorial.entries.filter(
    (entry) => entry.status !== "draft" && entry.status !== "rejected",
  );
  const cohorts = [
    { id: "all-triads" as const, entries },
    {
      id: "proper-names-only" as const,
      entries: entries.filter((entry) => entry.answer.kind === "proper"),
    },
  ];
  const cases: BenchmarkCase[] = [];
  const layouts = config.layouts.map((layout) => {
    const grid = compileLayout(layout);
    const lengths: Record<number, number> = {};
    for (const slot of grid.slots)
      lengths[slot.length] = (lengths[slot.length] ?? 0) + 1;
    return {
      ...layout,
      width: grid.width,
      height: grid.height,
      slots: grid.slots.length,
      whiteCells: grid.whiteCells.length,
      lengths,
      rotational: layout.rows.join("") === [...layout.rows.join("")].reverse().join(""),
    };
  });
  for (const layout of config.layouts)
    for (const cohort of cohorts) {
      const bank = cohort.entries.map((entry) => ({
        id: entry.id,
        grid: entry.answer.grid,
      }));
      for (const seed of config.seeds) {
        const started = onCase ? performance.now() : 0;
        const result = fillGrid(layout, bank, { seed, nodeLimit: config.nodeLimit });
        if (onCase)
          onCase({
            layoutId: layout.id,
            cohort: cohort.id,
            seed,
            elapsedMs: performance.now() - started,
          });
        if (
          result.status === "solved" &&
          inspectFill(layout, bank, result.placements).issues.length
        ) {
          throw new Error(`Search produced an invalid fill: ${layout.id}`);
        }
        cases.push({ layoutId: layout.id, cohort: cohort.id, seed, result });
      }
    }
  return {
    schemaVersion: 1 as const,
    mode: "unpublished-research" as const,
    algorithm: ALGORITHM_VERSION,
    inputSha256: sha256(JSON.stringify({ editorial, snapshot, config })),
    config,
    layouts,
    cohorts: cohorts.map((cohort) => ({
      id: cohort.id,
      entries: cohort.entries.length,
      distinctAnswers: new Set(cohort.entries.map((entry) => entry.answer.grid)).size,
    })),
    cases,
  };
}

export function benchmarkReport(benchmark: Benchmark, editorial: Editorial): string {
  const lines = [
    "# Seed fill benchmark",
    "",
    "Generated by `pnpm benchmark:run`. Unpublished research, not publication approval.",
    "",
    `Algorithm: \`${benchmark.algorithm}\`. Input SHA-256: \`${benchmark.inputSha256}\`.`,
    `Seeds: ${benchmark.config.seeds.join(", ")}. Budget: ${benchmark.config.nodeLimit.toLocaleString("en-US")} search states per case.`,
    "",
    "Search outcomes and work counts are deterministic. Wall-clock timing and machine details",
    "are recorded separately in `.cache/benchmarks/latest.json` when generating this report.",
    "CI replays the fixed work budget and checks this report; it does not assert timing thresholds.",
    "",
    "## Scope and interpretation",
    "",
    ...benchmark.cohorts.map(
      (cohort) =>
        `- ${cohort.id}: ${cohort.entries} eligible triads, ${cohort.distinctAnswers} distinct grid answers.`,
    ),
    "",
    "The proper-names-only control is a subset of this same sourced seed. It is not",
    "the historical unrestricted word list. Both cohorts use identical layouts, seeds and limits.",
    "Draft/rejected entries are excluded. Evidence-checked research entries remain unpublished.",
    "",
    "These original layouts sample open grids, clipped corners and blocked bridges/waists.",
    "They are diagnostic fixtures, not an exhaustive or representative survey of all crossword layouts.",
    "Symmetry is reported, not required. No unrestricted dictionary words are added.",
    "",
    "Unsatisfiable means this exact bank/layout is ruled out by a distinct-word length shortage",
    "or exhausted constraint search. Budget-exhausted means unvisited branches remain.",
    "Repeated seeds that stop before branching do not supply independent evidence.",
    "These results cannot establish a daily size, puzzle quality, or a sustainable number of dailies.",
    "",
    "## Layouts",
    "",
    "| Layout | Size | Slots | White cells | 180° symmetry | Slot lengths |",
    "| --- | --- | --- | --- | --- | --- |",
    ...benchmark.layouts.map(
      (layout) =>
        `| ${layout.id} | ${layout.width}×${layout.height} | ${layout.slots} | ${layout.whiteCells}/${layout.width * layout.height} | ${layout.rotational ? "yes" : "no"} | ${Object.entries(
          layout.lengths,
        )
          .map(([length, count]) => `${length}:${count}`)
          .join(", ")} |`,
    ),
    "",
    "## Outcomes",
    "",
    "| Layout | Cohort | Solved | Unsatisfiable | Limited | States (all seeds) | First diagnosis |",
    "| --- | --- | --- | --- | --- | --- | --- |",
  ];
  for (const layout of benchmark.layouts)
    for (const cohort of benchmark.cohorts) {
      const runs = benchmark.cases.filter(
        (run) => run.layoutId === layout.id && run.cohort === cohort.id,
      );
      const first = runs[0]!.result;
      const diagnosis = first.diagnostics.lengthDeficits.length
        ? first.diagnostics.lengthDeficits
            .map(
              (gap) => `${gap.length} letters: ${gap.slots} slots / ${gap.words} words`,
            )
            .join(", ")
        : first.diagnostics.deadEnds.length
          ? `Crossing/uniqueness contradiction at ${first.diagnostics.deadEnds[0]!.slotId}`
          : first.status === "solved"
            ? "Complete fill"
            : `${first.limit} budget`;
      lines.push(
        `| ${layout.id} | ${cohort.id} | ${runs.filter((run) => run.result.status === "solved").length} | ${runs.filter((run) => run.result.status === "unsatisfiable").length} | ${runs.filter((run) => run.result.status === "budget-exhausted").length} | ${runs.reduce((sum, run) => sum + run.result.stats.nodes, 0)} | ${diagnosis} |`,
      );
    }
  lines.push(
    "",
    "## Full-bank letter coverage",
    "",
    "Distinct eligible grid answers, grouped by total length. Word boundaries remain in the triads.",
    "Initial/final letters are coverage diagnostics, not a rule limiting future answers.",
    "",
    "| Length | Distinct words | Initial letters | Final letters |",
    "| --- | --- | --- | --- |",
  );
  const eligible = editorial.entries.filter(
    (entry) => entry.status !== "draft" && entry.status !== "rejected",
  );
  const distinct = [...new Set(eligible.map((entry) => entry.answer.grid))];
  for (const length of [...new Set(distinct.map((word) => word.length))].sort(
    (a, b) => a - b,
  )) {
    const words = distinct.filter((word) => word.length === length);
    const lettersAt = (index: number) =>
      [...new Set(words.map((word) => word[index]!))].sort().join("");
    lines.push(
      `| ${length} | ${words.length} | ${lettersAt(0)} | ${lettersAt(length - 1)} |`,
    );
  }
  lines.push(
    "",
    "## Crossing diagnostics for the full bank",
    "",
    "Most frequent retained dead end for the first seed in each layout that passed length preflight.",
    "Diagnostics retain up to eight examples from the first hundred distinct dead ends.",
    "Each bracket lists letters still supported by the crossing domain at that offset.",
    "An empty bracket has no support. A dot in the pattern means no single letter is fixed.",
    "These are conditional dead-end constraints, not guaranteed recipes for a new answer.",
    "Other candidate words could restore domains earlier in propagation. Do not sum deficits",
    "across different layouts or mistake an early failed slot for the only vocabulary gap.",
    "",
    "| Layout | Slot | Pattern | Supported letters by position |",
    "| --- | --- | --- | --- |",
  );
  for (const layout of benchmark.layouts) {
    const run = benchmark.cases.find(
      (item) => item.layoutId === layout.id && item.cohort === "all-triads",
    )!;
    const gap = run.result.diagnostics.deadEnds[0];
    if (gap)
      lines.push(
        `| ${layout.id} | ${gap.slotId} | \`${gap.pattern}\` | \`${gap.supports.map((letters) => `[${letters}]`).join("")}\` |`,
      );
  }
  lines.push("", "## Successful research examples", "");
  const entries = new Map(editorial.entries.map((entry) => [entry.id, entry]));
  for (const layout of benchmark.layouts) {
    const success = benchmark.cases.find(
      (run) =>
        run.layoutId === layout.id &&
        run.cohort === "all-triads" &&
        run.result.status === "solved",
    );
    if (!success) continue;
    const bank = editorial.entries.map((entry) => ({
      id: entry.id,
      grid: entry.answer.grid,
    }));
    const rendered = inspectFill(
      { id: layout.id, rows: layout.rows },
      bank,
      success.result.placements,
    );
    lines.push(
      `### ${layout.id}, seed ${success.seed}`,
      "",
      "```text",
      ...rendered.rows,
      "```",
      "",
      "| Slot | Answer | Enumeration | Clue | Hint |",
      "| --- | --- | --- | --- | --- |",
    );
    for (const placement of success.result.placements) {
      const entry = entries.get(placement.entryId)!;
      const escape = (text: string) =>
        text.replaceAll("|", "\\|").replaceAll("\n", " ");
      lines.push(
        `| ${placement.slotId} | ${escape(entry.answer.display)} | ${entry.answer.enumeration.join(",")} | ${escape(entry.clue.text)} | ${escape(entry.hint.text)} |`,
      );
    }
    lines.push("");
  }
  if (
    !benchmark.cases.some(
      (run) => run.cohort === "all-triads" && run.result.status === "solved",
    )
  )
    lines.push("No complete fill was found for the full seed in these layouts.", "");
  lines.push(
    "## Next decision",
    "",
    "Expand the sourced, clue-backed bank using length demand and crossing-letter coverage.",
    "Research ordinary Warcraft-connected vocabulary as well as familiar names; keep",
    "multi-word answers and preserve their enumerations. Rerun the same fixtures after",
    "each batch. Add further valid layouts where these fixtures overconcentrate a length.",
    "Even a successful fill still needs editorial checks for clues disclosing one another,",
    "repeated lore facts, faction bias, fair crossings and an actual cold solve.",
    "",
  );
  return lines.join("\n");
}
