import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { format, resolveConfig } from "prettier";
import { prepareResearchPuzzle } from "./research-puzzle.ts";

const read = (path: string): unknown => JSON.parse(readFileSync(path, "utf8"));
const catalogue = read("content/seed/editorial.json");
const evidence = read("content/seed/evidence.json");
const trials = [
  {
    id: "first-steps",
    label: "Easy",
    portable: "playtest",
    report: "prototype-report",
    notes: [
      "The owner reports completing this puzzle blind, finding it interesting but easy. No solve time or assistance counts were supplied. This is one player's feedback, not publication approval.",
      "The oversized heading, promotional copy and process commentary were removed after feedback. Instructions remain available on demand.",
      "The shape is irregular. The longest answer has a three-letter stretch without crossing help, and some five-letter answers have two checked letters.",
    ],
  },
  {
    id: "medium-steps",
    label: "Medium",
    portable: "medium",
    report: "medium-report",
    notes: [
      "Fifteen entries use existing familiar answers, with no answer overlap with the first puzzle. Fifteen alternate triads retain traceable facts and hints. Eleven clues are provisionally medium, four easy footholds. The overall Medium label is a hypothesis until a blind solve.",
      "Difficulty comes from less direct references, relationships and double meanings. No obscure loot, quest-title recall or fabricated facts were added. Some clues can still be solved through ordinary English or known game mechanics.",
      "The same construction floor and player apply to both trials. Actual checking differs between layouts and is reported below. Its longest entry has unchecked stretches, which need human assessment.",
    ],
  },
];
const output = ".cache/prototype";
mkdirSync(output, { recursive: true });
const compiled = new Map<string, string>();
for (const name of ["player", "model"]) {
  const { outputText } = ts.transpileModule(readFileSync(`web/${name}.ts`, "utf8"), {
    compilerOptions: { target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext },
  });
  writeFileSync(`${output}/${name}.js`, outputText);
  compiled.set(name, outputText);
}
const style = readFileSync("web/style.css", "utf8");
writeFileSync(`${output}/style.css`, style);
const standalonePlayer = ts.transpileModule(readFileSync("web/player.ts", "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext },
  transformers: {
    before: [
      () => (source) =>
        ts.factory.updateSourceFile(
          source,
          source.statements.filter((statement) => !ts.isImportDeclaration(statement)),
        ),
    ],
  },
}).outputText;
for (const trial of trials) {
  const { playable, measurements, grid } = prepareResearchPuzzle(
    read(`content/puzzles/${trial.id}.json`),
    catalogue,
    evidence,
  );
  const html = readFileSync("web/index.html", "utf8")
    .replace("__PUZZLE_JSON__", JSON.stringify(playable).replace(/</g, "\\u003c"))
    .replace("__DIFFICULTY__", trial.label);
  writeFileSync(
    `${output}/${trial.id === "first-steps" ? "index" : "medium-index"}.html`,
    html,
  );
  writeFileSync(
    `${output}/${trial.portable}.html`,
    html
      .replace(
        '<link rel="stylesheet" href="/style.css" />',
        () => `<style>${style}</style>`,
      )
      .replace(
        '<script src="/player.js" type="module"></script>',
        () =>
          `<script type="module">${compiled.get("model")}\n${standalonePlayer}</script>`,
      ),
  );
  const crossed = new Set(
    grid.slots.flatMap((slot) =>
      slot.crossings.map((crossing) => slot.cells[crossing.offset]),
    ),
  ).size;
  const rawReport = [
    `# ${trial.label} construction trial`,
    "",
    "Generated by `pnpm prototype:build`. Research only, with no cold-solve publication approval.",
    "",
    `Layout: ${playable.width} columns × ${playable.height} rows. ${playable.entries.length} entries, ${grid.whiteCells.length} white cells, ${crossed} crossing cells.`,
    "",
    "Checking below is per answer. A crossing is counted in each of the two answers it helps. Every entry has at least two crossings and 40% checking. This remains a provisional research floor, not an established fairness standard.",
    "",
    "| Entry | Letters | Checked | Coverage |",
    "| --- | --- | --- | --- |",
    ...measurements.map(
      (m) =>
        `| ${m.slotId} | ${m.length} | ${m.checked} | ${Math.round((m.checked / m.length) * 100)}% |`,
    ),
    "",
    "## Review and feedback",
    "",
    ...trial.notes.flatMap((note) => [note, ""]),
    "## Benchmark interpretation",
    "",
    "Partially checked grids are the primary format. The fill benchmark now includes this exact layout and independently searches the bank for a complete fill. The authored placement is validated separately. Search may choose different answers and does not review clue fairness.",
    "Fully checked layouts remain a comparison. Their failure does not mean no playable crossword exists. See [the split results](fill-benchmark.md).",
    "",
    "## Next gate",
    "",
    "Blind-solve the Medium trial before constructing the other five pilot puzzles. Record time, assistance, ambiguous clues and the usefulness of crossings. One complete fill and one positive solve do not establish sustainable daily production.",
    "",
  ].join("\n");
  const reportPath = `docs/${trial.report}.md`;
  const report = await format(rawReport, {
    ...(await resolveConfig(reportPath)),
    parser: "markdown",
  });
  if (process.argv.includes("--check")) {
    if (readFileSync(reportPath, "utf8") !== report)
      throw new Error(`Stale report: ${reportPath}`);
  } else writeFileSync(reportPath, report);
  console.log(
    `Built ${trial.label} trial: ${playable.entries.length} entries, ${crossed}/${grid.whiteCells.length} distinct cells checked.`,
  );
}
