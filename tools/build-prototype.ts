import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import ts from "typescript";
import { format, resolveConfig } from "prettier";
import { prepareResearchPuzzle } from "./research-puzzle.ts";

const read = (path: string): unknown => JSON.parse(readFileSync(path, "utf8"));
const { playable, measurements, grid } = prepareResearchPuzzle(
  read("content/puzzles/first-steps.json"),
  read("content/seed/editorial.json"),
  read("content/seed/evidence.json"),
);
const output = ".cache/prototype";
mkdirSync(output, { recursive: true });
const compiled = new Map<string, string>();
for (const name of ["player", "model"]) {
  const { outputText } = ts.transpileModule(readFileSync(`web/${name}.ts`, "utf8"), {
    compilerOptions: { target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext },
  });
  writeFileSync(`${output}/${name}.js`, outputText);
  compiled.set(name, outputText);
}
writeFileSync(`${output}/style.css`, readFileSync("web/style.css"));
writeFileSync(
  `${output}/index.html`,
  readFileSync("web/index.html", "utf8").replace(
    "__PUZZLE_JSON__",
    JSON.stringify(playable).replace(/</g, "\\u003c"),
  ),
);
// Portable playtest: same source and state model, no server or remote assets needed.
const standalonePlayer = ts.transpileModule(readFileSync("web/player.ts", "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext },
  transformers: {
    before: [
      () => (source) =>
        ts.factory.updateSourceFile(
          source,
          source.statements.filter((statement) => !ts.isImportDeclaration(statement)),
        ),
    ],
  },
}).outputText;
writeFileSync(
  `${output}/playtest.html`,
  readFileSync(`${output}/index.html`, "utf8")
    .replace(
      '<link rel="stylesheet" href="/style.css" />',
      () => `<style>${readFileSync("web/style.css", "utf8")}</style>`,
    )
    .replace(
      '<script src="/player.js" type="module"></script>',
      () =>
        `<script type="module">${compiled.get("model")}\n${standalonePlayer}</script>`,
    ),
);
const crossed = new Set(
  grid.slots.flatMap((s) => s.crossings.map((c) => s.cells[c.offset])),
).size;
console.log(
  `Built local research puzzle: ${playable.entries.length} entries, ${crossed}/${grid.whiteCells.length} distinct cells checked.`,
);
const rawReport = [
  "# First playable construction trial",
  "",
  "Generated by `pnpm prototype:build`. Research only, with no cold-solve approval.",
  "",
  `Layout: ${playable.width} columns × ${playable.height} rows. ${playable.entries.length} entries, ${grid.whiteCells.length} white cells, ${crossed} crossing cells.`,
  "",
  "Checking below is per answer. A crossing is counted in each of the two answers it helps.",
  "Every entry has at least two crossings and at least 40% checking. This is an experimental floor, not an established fairness standard.",
  "",
  "| Entry | Letters | Checked | Coverage |",
  "| --- | --- | --- | --- |",
  ...measurements.map(
    (m) =>
      `| ${m.slotId} | ${m.length} | ${m.checked} | ${Math.round((m.checked / m.length) * 100)}% |`,
  ),
  "",
  "## Interpretation",
  "",
  "One complete arrangement exists within the current 342-answer bank when some letters may be unchecked. No vocabulary was added for this trial.",
  "The layout was composed around selected words. It is not part of the fixed fully checked benchmark, whose negative results remain valid.",
  "",
  "The main-agent source/wording pass found no direct answer disclosures across the selected clues or hints. It is not a cold solve.",
  "The grid has an irregular outline and uneven crossing support. Molten Core has a three-letter stretch without crossing help. Elune and QUEEN each have only two checked letters.",
  "SHAMAN and SLAVE both involve Thrall but ask separate facts. The trial deliberately mixes ordinary vocabulary with familiar Warcraft identities. Human playtesting must decide whether that balance is satisfying.",
  "",
  "## Next gate",
  "",
  "Cold-solve this puzzle before composing the remaining six pilot puzzles. Record unassisted progress, ambiguous clues, hint/reveal use and which unchecked stretches cause trouble.",
  "A complete fill proves construction possibility for this example. It does not prove clue fairness, repeatable production cost or sustainable dailies.",
  "",
].join("\n");
const reportPath = "docs/prototype-report.md";
const report = await format(rawReport, {
  ...(await resolveConfig(reportPath)),
  parser: "markdown",
});
if (process.argv.includes("--check")) {
  if (readFileSync(reportPath, "utf8") !== report)
    throw new Error("Prototype report is stale");
} else writeFileSync(reportPath, report);
