import {
  copyFileSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  writeFileSync,
} from "node:fs";
import ts from "typescript";
import { format, resolveConfig } from "prettier";
import { preparePilot, trialAsset, trialRoute } from "./pilot.ts";

const read = (path: string): unknown => JSON.parse(readFileSync(path, "utf8"));
const catalogue = read("content/seed/editorial.json");
const evidence = read("content/seed/evidence.json");
const pilot = preparePilot(
  read("content/puzzles/pilot.json"),
  (id) => read(`content/puzzles/${id}.json`),
  catalogue,
  evidence,
);
const trials = pilot.trials;
const output = ".cache/prototype";
mkdirSync(output, { recursive: true });
const compiled = new Map<string, string>();
for (const name of ["player", "model"]) {
  const { outputText } = ts.transpileModule(readFileSync(`web/${name}.ts`, "utf8"), {
    compilerOptions: { target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext },
  });
  writeFileSync(`${output}/${name}.js`, outputText);
  compiled.set(name, outputText);
}
const style = readFileSync("web/style.css", "utf8");
writeFileSync(`${output}/style.css`, style);
mkdirSync(`${output}/fonts`, { recursive: true });
const fonts = readdirSync("web/fonts").filter((name) => name.endsWith(".woff2"));
for (const name of fonts) copyFileSync(`web/fonts/${name}`, `${output}/fonts/${name}`);
/** The crest on the tab: a gold diamond on the night. */
const favicon =
  '<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 32 32"><rect width="32" height="32" rx="6" fill="#120d09"/><path d="M16 4l11 12-11 12L5 16z" fill="#c9a227"/><path d="M16 9l6 7-6 7-6-7z" fill="#2a1d12"/></svg>';
writeFileSync(`${output}/favicon.svg`, favicon);
/** The offline files carry their fonts and icon inside, so they need no server. */
const standaloneStyle = style.replace(
  /url\("\/fonts\/([^"]+)"\)/g,
  (_, name: string) =>
    `url("data:font/woff2;base64,${readFileSync(`web/fonts/${name}`).toString("base64")}")`,
);
const inlineIcon = `data:image/svg+xml;base64,${Buffer.from(favicon).toString("base64")}`;
const standalonePlayer = ts.transpileModule(readFileSync("web/player.ts", "utf8"), {
  compilerOptions: { target: ts.ScriptTarget.ES2024, module: ts.ModuleKind.ESNext },
  transformers: {
    before: [
      () => (source) =>
        ts.factory.updateSourceFile(
          source,
          source.statements.filter((statement) => !ts.isImportDeclaration(statement)),
        ),
    ],
  },
}).outputText;
for (const trial of trials) {
  const { playable, measurements, grid } = trial;
  const html = readFileSync("web/index.html", "utf8")
    .replace(
      "<title>Warcraft crossword</title>",
      `<title>${trials.indexOf(trial) + 1}. ${trial.label} · Warcraft crossword</title>`,
    )
    .replace("__PUZZLE_JSON__", () => JSON.stringify(playable).replace(/</g, "\\u003c"))
    .replace("__DIFFICULTY__", () => trial.label);
  const normalHtml = html.replaceAll("__PILOT_LINK__", "/pilot");
  const portableHtml = html.replaceAll("__PILOT_LINK__", "pilot.html");
  writeFileSync(`${output}/${trialAsset(trial)}`, normalHtml);
  writeFileSync(
    `${output}/${trial.portable}.html`,
    portableHtml
      .replace(
        '<link rel="stylesheet" href="/style.css" />',
        () => `<style>${standaloneStyle}</style>`,
      )
      .replace(
        '<link rel="icon" href="/favicon.svg" type="image/svg+xml" />',
        () => `<link rel="icon" href="${inlineIcon}" type="image/svg+xml" />`,
      )
      .replace(
        '<script src="/player.js" type="module"></script>',
        () =>
          `<script type="module">${compiled.get("model")}\n${standalonePlayer}</script>`,
      ),
  );
  const crossed = new Set(
    grid.slots.flatMap((slot) =>
      slot.crossings.map((crossing) => slot.cells[crossing.offset]),
    ),
  ).size;
  const rawReport = [
    `# ${trial.label} construction trial: ${trial.id}`,
    "",
    "Generated by `pnpm prototype:build`. Research only, with no cold-solve publication approval.",
    "",
    `Layout: ${playable.width} columns × ${playable.height} rows. ${playable.entries.length} entries, ${grid.whiteCells.length} white cells, ${crossed} crossing cells.`,
    "",
    "Checking below is per answer. A crossing is counted in each of the two answers it helps. Every entry has at least two crossings and 40% checking. This remains a provisional research floor, not an established fairness standard.",
    "",
    "| Entry | Letters | Checked | Coverage |",
    "| --- | --- | --- | --- |",
    ...measurements.map(
      (m) =>
        `| ${m.slotId} | ${m.length} | ${m.checked} | ${Math.round((m.checked / m.length) * 100)}% |`,
    ),
    "",
    "## Review and feedback",
    "",
    ...trial.notes.flatMap((note) => [note, ""]),
    "## Benchmark interpretation",
    "",
    "Partially checked grids are the primary format. The fill benchmark now includes this exact layout and independently searches the bank for a complete fill. The authored placement is validated separately. Search may choose different answers and does not review clue fairness.",
    "Fully checked layouts remain a comparison. Their failure does not mean no playable crossword exists. See [the split results](fill-benchmark.md).",
    "",
    "## Next gate",
    "",
    "Blind-solve the five new trials. Record time, assistance, ambiguous clues and the usefulness of crossings. Seven candidate puzzles and feedback from one solver do not establish sustainable daily production.",
    "",
  ].join("\n");
  const reportPath = `docs/${trial.report}.md`;
  const report = await format(rawReport, {
    ...(await resolveConfig(reportPath)),
    parser: "markdown",
  });
  if (process.argv.includes("--check")) {
    if (readFileSync(reportPath, "utf8") !== report)
      throw new Error(`Stale report: ${reportPath}`);
  } else writeFileSync(reportPath, report);
  console.log(
    `Built ${trial.label} trial: ${playable.entries.length} entries, ${crossed}/${grid.whiteCells.length} distinct cells checked.`,
  );
}

const gems = {
  Easy: "\u25c6\u25c7\u25c7",
  Medium: "\u25c6\u25c6\u25c7",
  Hard: "\u25c6\u25c6\u25c6",
};
const links = (portable: boolean) =>
  trials
    .map(
      (trial, index) =>
        `<li><a href="${portable ? trial.portable + ".html" : trialRoute(trial)}"><span class="no">${index + 1}</span> <span class="level">${trial.label}</span> <span class="gems" aria-hidden="true">${gems[trial.label]}</span> <span class="meta">${trial.playable.entries.length} clues, ${trial.playable.width} by ${trial.playable.height}</span></a></li>`,
    )
    .join("");
const indexPage = (portable: boolean) =>
  `<!doctype html><html lang="en"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover"><meta name="theme-color" content="#120d09"><title>Crosswords</title>${portable ? `<link rel="icon" href="${inlineIcon}" type="image/svg+xml"><style>${standaloneStyle}</style>` : '<link rel="icon" href="/favicon.svg" type="image/svg+xml"><link rel="stylesheet" href="/style.css">'}</head><body><main class="archive"><header class="masthead"><h1 class="title-gilded">Warcraft crossword</h1><p class="rule" aria-hidden="true"></p></header><p class="archive-intro">${trials.length} trial puzzles. Choose one and type straight into the grid. Your letters are saved on this device.</p><ol class="pilot-list">${links(portable)}</ol><footer>Unofficial Warcraft fan project. Not affiliated with Blizzard Entertainment.</footer></main></body></html>`;
writeFileSync(`${output}/pilot.html`, indexPage(true));
writeFileSync(`${output}/pilot-index.html`, indexPage(false));
const summary = [
  "# Seven-puzzle pilot",
  "",
  "Generated by `pnpm prototype:build`. These are unpublished candidates. The first Easy and Medium have owner-reported blind solves. No formal entry or grid publication approvals are granted.",
  "",
  "| Trial | Target | Entries | Crossing cells / white cells | Blind feedback |",
  "| --- | --- | --- | --- | --- |",
  ...trials.map(
    (trial, i) =>
      `| ${i + 1} | ${trial.label} | ${trial.playable.entries.length} | ${new Set(trial.grid.slots.flatMap((s) => s.crossings.map((c) => s.cells[c.offset]))).size}/${trial.grid.whiteCells.length} | ${i === 0 ? "Interesting, easy" : i === 1 ? "Challenging but fair, crossings helped" : "Pending"} |`,
  ),
  "",
  `There are ${pilot.totalEntries} answer slots and ${pilot.occurrences.size} distinct answers. ${[...pilot.occurrences.values()].filter((v) => v.length > 1).length} answers recur, with a maximum of ${Math.max(...[...pilot.occurrences.values()].map((v) => v.length))} appearances.`,
  "",
  `Exact block patterns: ${new Set(trials.map((t) => t.puzzle.layout.rows.join("\n"))).size}. Related patterns are allowed. Each exact layout is validated and independently searched in the fill benchmark.`,
  "",
  "## Interpretation",
  "",
  "The mix is two Easy, three Medium and two Hard candidates. New labels are provisional. Hard combines deeper lore associations with familiar answers and easier footholds, rather than making every clue obscure. Grid sizes and checking also vary, so solve-time differences cannot be assigned to clue wording alone.",
  "",
  "The two existing solve identities remain unchanged. Each artifact uses its own puzzle ID and content fingerprint. The compact index is navigation only, with no new reward or account system.",
  "",
  "## Construction and sources",
  "",
  "All answers come from the existing 342-answer bank. New clue/hint variants use reviewed existing passages, not unreferenced recollections or later-era facts. Source coverage remains primarily Vanilla and does not constitute a complete TBC/Wrath audit.",
  "",
  "Word-led exploratory searches were followed by source reading, clue writing, cross-prompt review and independent layout/fill validation. Rejected search attempts are not scored as successful puzzles. Exact candidate layouts and placements are committed; the exploratory scratch scripts are not a production generator.",
  "",
  "Editorial time was not measured with a production stopwatch. A manual five-puzzle batch is not evidence of a sustainable daily pipeline. The next assessment needs actual cold-solve results, measured construction/editing effort and repeat spacing over a longer sample.",
  "",
  "## Answer reuse (spoilers)",
  "",
  "| Answer | Trials |",
  "| --- | --- |",
  ...[...pilot.occurrences]
    .filter(([, editions]) => editions.length > 1)
    .map(([answer, editions]) => `| ${answer} | ${editions.join(", ")} |`),
  "",
].join("\n");
const summaryPath = "docs/pilot-report.md";
const formatted = await format(summary, {
  ...(await resolveConfig(summaryPath)),
  parser: "markdown",
});
if (process.argv.includes("--check")) {
  if (readFileSync(summaryPath, "utf8") !== formatted)
    throw new Error("Stale pilot report");
} else writeFileSync(summaryPath, formatted);
